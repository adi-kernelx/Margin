"""Tests for row building, column (gutter) detection and line-level heading
evidence in extract_blocks.py, using synthetic spans instead of real PDFs."""

from ml.data.extract_blocks import (
    SpanInfo,
    build_visual_lines,
    group_lines_into_blocks,
    line_heading,
)
from ml.data.heading_rules import detect_heading

PAGE_W = 600.0
BODY = "CMR10"


def span(text, x0, y0, x1=None, size=10.0, font=BODY, bold=False):
    x1 = x1 if x1 is not None else x0 + 5.0 * len(text)
    return SpanInfo(text=text, bbox=(x0, y0, x1, y0 + size), font_name=font,
                    font_size=size, bold=bold, italic=False, mono=False)


def maths_line(y, words):
    """A full-width line made of many small spans on both sides of the centre,
    like a maths paper where every symbol is its own span."""
    spans, x = [], 60.0
    for w in words:
        spans.append(span(w, x, y))
        x += 5.0 * len(w) + 6.0   # word gap (~6pt) is far below a gutter
    return spans


def texts(lines):
    return [li.text for li in lines]


class TestColumns:
    def test_single_column_maths_page_keeps_word_order(self):
        words = ["Let", "x", "∈", "R", "and", "suppose", "f", "(", "x", ")",
                 "is", "convex", "on", "the", "whole", "domain", "D", "here"]
        spans = []
        for k in range(10):
            spans += maths_line(80 + 14 * k, words)
        n_cols, lines = build_visual_lines(spans, 0, 1, PAGE_W)
        assert n_cols == 1
        assert len(lines) == 10
        assert lines[0].text == " ".join(words)

    def test_two_column_page_reads_left_then_right(self):
        spans = []
        for k in range(10):
            y = 80 + 14 * k
            spans.append(span(f"left line {k} text", 40, y, 270))
            spans.append(span(f"right line {k} text", 330, y, 560))
        n_cols, lines = build_visual_lines(spans, 0, 1, PAGE_W)
        assert n_cols == 2
        assert texts(lines)[:2] == ["left line 0 text", "left line 1 text"]
        assert texts(lines)[10] == "right line 0 text"

    def test_subscript_joins_its_line_without_chaining(self):
        spans = [
            span("the iterate x", 60, 100, 160),
            span("k+1", 161, 105, 175, size=7.0),       # subscript
            span("converges to x*", 178, 100, 300),
            span("and the next line starts here", 60, 114, 300),
        ]
        _, lines = build_visual_lines(spans, 0, 1, PAGE_W)
        assert texts(lines) == ["the iterate x k+1 converges to x*",
                                "and the next line starts here"]


    def test_tall_bracket_does_not_merge_neighbouring_lines(self):
        spans = [
            span("first line of the paragraph", 60, 100, 300),
            span("second line of the paragraph", 60, 112, 300),
            # A big delimiter whose box covers both lines.
            SpanInfo(text="{", bbox=(305, 98, 312, 124), font_name="CMEX10",
                     font_size=10.0, bold=False, italic=False, mono=False),
        ]
        _, lines = build_visual_lines(spans, 0, 1, PAGE_W)
        assert [li.text for li in lines][:2] == ["first line of the paragraph {",
                                                "second line of the paragraph"] or \
               [li.text for li in lines][:2] == ["first line of the paragraph",
                                                "second line of the paragraph {"]


class TestHeadingEvidence:
    def _lines(self, rows):
        spans = []
        for k, row in enumerate(rows):
            spans += [span(t, x, 100 + 14 * k, font=f, bold=b) for t, x, f, b in row]
        _, lines = build_visual_lines(spans, 0, 1, PAGE_W)
        return lines

    def test_theorem_then_proof_split_into_two_blocks(self):
        lines = self._lines([
            [("Theorem 1.", 60, "CMBX10", True), ("A holds for all x.", 120, BODY, False)],
            [("Proof.", 60, "CMTI10", False), ("Trivial.", 100, BODY, False)],
        ])
        blocks = group_lines_into_blocks(lines, PAGE_W, 800, 1, False, BODY)
        assert len(blocks) == 2

    def test_wrapped_reference_is_not_a_heading(self):
        lines = self._lines([
            [("Every set is generated by Construction", 60, BODY, False)],
            [("Lemma 4.6 excludes additional vertices on the two sides.", 60, BODY, False)],
        ])
        assert line_heading(lines[1], lines[0], BODY) is None
        blocks = group_lines_into_blocks(lines, PAGE_W, 800, 1, False, BODY)
        assert len(blocks) == 1

    def test_formatted_heading_after_unfinished_line_still_counts(self):
        lines = self._lines([
            [("which completes the construction", 60, BODY, False)],
            [("Lemma 4.7.", 60, "CMBX10", True), ("Every vertex is interior.", 120, BODY, False)],
        ])
        h = line_heading(lines[1], lines[0], BODY)
        assert h is not None and h.weak_subtype == "lemma"


class TestNewFalsePositives:
    def test_algorithm_reference_with_letter(self):
        assert detect_heading("Algorithm B creates the BasicPub public key", is_bold=True) is None

    def test_algorithm_name_without_parenthesis(self):
        assert detect_heading("Algorithm MapToPoint works as follows", has_font_change=True) is None

    def test_algorithm_named_with_parenthesis_and_bold(self):
        h = detect_heading("Algorithm BitsToBytes(b)", is_bold=True)
        assert h is not None and h.weak_label == "algorithm"

    def test_section_title_with_of(self):
        assert detect_heading("DEFINITION OF A FINITE AUTOMATON", is_uppercase=True) is None

    def test_proof_of_still_allowed(self):
        assert detect_heading("Proof of Lemma 3.") is not None

    def test_proof_of_dotted_number_kept_whole(self):
        h = detect_heading("Proof of Theorem 4.1. The theorem follows from Lemma 4.2.")
        assert h is not None and h.heading_text == "Proof of Theorem 4.1."

    def test_appendix_number(self):
        h = detect_heading("Lemma B.1. There is an algorithm D.")
        assert h is not None and h.heading_number == "B.1"


class TestSecondRoundRules:
    def test_numbered_reference_with_lowercase_verb(self):
        assert detect_heading("Algorithm 1 outlines the procedure by which Alice pays") is None
        assert detect_heading("Lemma 4.6 excludes additional vertices", has_font_change=True) is None

    def test_numbered_heading_with_title_still_detected(self):
        h = detect_heading("Algorithm 2 Offline Contract Payment Transaction", is_bold=True)
        assert h is not None and h.weak_label == "algorithm"

    def test_toc_without_leaders(self):
        from ml.data.heading_rules import is_toc_entry
        assert is_toc_entry("12 Information Gain 20")
        assert not is_toc_entry("2 Definitions")
        assert not is_toc_entry("Let n be at least 3")

    def test_double_spaced_paragraph_is_one_block(self):
        rows = ["We propose risk rectification and the idea is simple",
                "to state: we keep the calibration step but change",
                "the parameter on which it operates across levels.",
                "Paper Outline. Section 2 reviews the method and"]
        spans = []
        for k, t in enumerate(rows):
            x1 = 300 if k == 2 else 540   # third line is a short paragraph end
            spans.append(span(t, 72, 100 + 26 * k, x1))
        _, lines = build_visual_lines(spans, 0, 1, PAGE_W)
        blocks = group_lines_into_blocks(lines, PAGE_W, 800, 1, False, BODY)
        assert [len(b.lines) for b in blocks] == [3, 1]

    def test_spaced_underscore_function_name(self):
        h = detect_heading("Algorithm 7 wots _ sign ( M , SK .seed, PK .seed, ADRS )", is_bold=True)
        assert h is not None and h.heading_number == "7"
